import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const folders = ["images", "videos"];

const supported = new Set([
	".jpg",
	".jpeg",
	".png",
	".webp",
	".avif",
	".gif",
	".mp4",
	".webm",
]);

const manifest = {};

for (const folder of folders) {
	const directory = path.join(
		process.cwd(),
		"public",
		"creative-studio",
		folder,
	);

	let entries = [];

	try {
		entries = await readdir(directory, {
			withFileTypes: true,
		});
	} catch (error) {
		if (error.code !== "ENOENT") {
			throw error;
		}
	}

	manifest[folder] = entries
		.filter(
			(entry) =>
				entry.isFile() &&
				!entry.name.startsWith(".") &&
				supported.has(path.extname(entry.name).toLowerCase()),
		)
		.map((entry) => entry.name)
		.sort((a, b) =>
			a.localeCompare(b, "en", {
				numeric: true,
			}),
		);
}

const output = path.join(
	process.cwd(),
	"src",
	"data",
	"creativeMediaManifest.ts",
);

await mkdir(path.dirname(output), {
	recursive: true,
});

await writeFile(
	output,
	`// Automatically generated by scripts/generate-creative-media.mjs.\n` +
		`export const creativeMediaManifest: Record<string, string[]> = ${JSON.stringify(
			manifest,
			null,
			2,
		)};\n`,
	"utf8",
);

console.log(
	"Creative Studio manifest generated:",
	Object.values(manifest).reduce((sum, files) => sum + files.length, 0),
	"files",
);
